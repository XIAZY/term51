// Port of src/unicode/lut.zig (Ghostty v1.3.1).
//
// File naming: lut.zig is in src/unicode, outside src/terminal; it is in
// package terminal because Terminal.zig and Screen.zig use the unicode
// module. As for os_string_encoding.go, the directory is part of the name:
// the file is `unicode_lut.go` and its prefix is `UnicodeLut`
// (`unicode.lut.Tables` is `UnicodeLutTables`).
//
// Ported: `Tables(Elem)`, the reader of a 3-level lookup table, with both
// of its functions (`get` and `writeZig`).
//
// Not ported: `Generator(Elem, Context)`, which builds the three stages from
// a per-codepoint function at build time. libghostty-vt only reads tables
// generated by the Zig build (src/build/UnicodeTables.zig runs
// unicode/props_uucode.zig, which uses Generator with uucode's data); the
// Go port embeds those generated stages byte for byte instead of
// regenerating them (project lead decision; see unicode_props_table.go),
// so nothing calls a generator. lut.zig has no tests.

package terminal

import "fmt"

// This whole file is based on the algorithm described here:
// https://here-be-braces.com/fast-lookup-of-unicode-properties/

// UnicodeLutTables is lut.Tables(Elem): given a 3-level lookup table, can be
// used to look up a mapping for a given codepoint, encode it out to Zig,
// etc.
//
// Zig: a function returning a struct type; Go: a generic struct.
type UnicodeLutTables[Elem any] struct {
	stage1 []uint16
	stage2 []uint16
	stage3 []Elem
}

// Get returns the mapping for the given codepoint.
//
// Zig: `pub inline fn get(self: *const Self, cp: u21) Elem`. cp is a u21
// in Zig; the Go parameter is a uint32 and a value above maxInt(u21) cannot
// exist in Zig, so the port stops on it (assert) instead of reading an
// unrelated entry.
func (self *UnicodeLutTables[Elem]) Get(cp uint32) Elem {
	assert(cp <= 0x1FFFFF)
	high := cp >> 8
	low := cp & 0xFF
	return self.stage3[self.stage2[uint32(self.stage1[high])+low]]
}

// WriteZig writes the lookup table as Zig to the given writer. The
// written file exports three constants: stage1, stage2, and stage3. These
// can be used to rebuild the lookup table in Zig.
//
// Zig formats each stage3 entry with `{f}` when Elem is a struct with a
// `format` declaration (@typeInfo, @hasDecl) and with `{}` otherwise. Go:
// an Elem with a `Format() string` method (mapping.md: `{f}` is
// `Format() string`) uses it; any other Elem is printed with fmt.Sprint,
// which is what `{}` prints for the integers and bools used as table
// elements.
func (self *UnicodeLutTables[Elem]) WriteZig(writer *oscWriter) error {
	if err := writer.writeAll([]uint8("//! This file is auto-generated. Do not edit.\n" +
		"\n" +
		"pub fn Tables(comptime Elem: type) type {\n" +
		"    return struct {\n" +
		"pub const stage1: [" + itoa(uint64(len(self.stage1))) + "]u16 = .{")); err != nil {
		return err
	}
	for _, entry := range self.stage1 {
		if err := writer.writeAll([]uint8(itoa(uint64(entry)) + ",")); err != nil {
			return err
		}
	}

	if err := writer.writeAll([]uint8("\n" +
		"};\n" +
		"\n" +
		"pub const stage2: [" + itoa(uint64(len(self.stage2))) + "]u16 = .{")); err != nil {
		return err
	}
	for _, entry := range self.stage2 {
		if err := writer.writeAll([]uint8(itoa(uint64(entry)) + ",")); err != nil {
			return err
		}
	}
	if err := writer.writeAll([]uint8("};")); err != nil {
		return err
	}

	if err := writer.writeAll([]uint8("\n" +
		"pub const stage3: [" + itoa(uint64(len(self.stage3))) + "]Elem = .{")); err != nil {
		return err
	}
	for _, entry := range self.stage3 {
		var s string
		if f, ok := any(entry).(interface{ Format() string }); ok {
			s = f.Format()
		} else {
			s = fmt.Sprint(entry)
		}
		if err := writer.writeAll([]uint8(s + ",")); err != nil {
			return err
		}
	}
	return writer.writeAll([]uint8("};\n" +
		"    };\n" +
		"}\n"))
}
